import { mkdirSync, writeFileSync } from 'node:fs';
import assert from 'node:assert/strict';
import { chromium } from 'playwright';

const out = new URL('../../evidence/qa/', import.meta.url);
mkdirSync(out, { recursive: true });
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 900 }, deviceScaleFactor: 1 });
const errors = [];
page.on('pageerror', error => errors.push(error.message));
await page.goto(process.env.BOLGE_BASE_URL ?? 'http://127.0.0.1:1420', { waitUntil: 'domcontentloaded' });
await page.locator('.app-shell').waitFor();
await page.screenshot({ path: new URL('browser-start.png', out).pathname });
const buttons = await page.locator('button').allTextContents();
writeFileSync(new URL('browser-discovery.json', out), JSON.stringify({ title: await page.title(), buttons, errors }, null, 2));
await page.getByRole('button', { name: '회귀 예제 열기' }).click();
await page.getByText('87 cells').waitFor();
await page.screenshot({ path: new URL('browser-example.png', out).pathname });
for (let index = 0; index < 3; index++) await page.getByRole('button', { name: 'Step', exact: true }).click();
await page.getByText('WAITING_INPUT', { exact: false }).first().waitFor();
await page.getByRole('textbox', { name: '입력 데이터' }).fill('ABC');
await page.getByRole('checkbox', { name: 'LF 추가' }).check();
await page.getByRole('button', { name: '전송' }).click();
await page.getByRole('button', { name: 'Step', exact: true }).click();
await page.getByText('M[78] 84 → 29487').first().waitFor();
await page.screenshot({ path: new URL('browser-step4.png', out).pathname });
await page.locator('.toolbar-actions button.primary').click();
await page.getByText('HALTED · HALT_OPCODE').first().waitFor();
const registers = await page.locator('.register strong').allTextContents();
assert.deepEqual(registers, ['29514', '23', '80']);
assert.equal(await page.locator('.output-box').textContent(), 'J');
await page.screenshot({ path: new URL('browser-halted.png', out).pathname });
await page.getByRole('button', { name: 'Back', exact: true }).click();
await page.getByRole('button', { name: 'Step', exact: true }).click();
await page.getByText('HALTED · HALT_OPCODE').first().waitFor();
assert.equal(await page.locator('.output-box').textContent(), 'J');
await page.getByRole('tab', { name: 'Memory', exact: true }).click();
await page.getByPlaceholder('0–59048').fill('78');
await page.getByPlaceholder('0–59048').press('Enter');
await page.getByText('29514', { exact: true }).first().waitFor();
await page.screenshot({ path: new URL('browser-memory.png', out).pathname });
await page.setViewportSize({ width: 900, height: 650 });
await page.screenshot({ path: new URL('browser-compact.png', out).pathname });
assert.deepEqual(errors, []);
writeFileSync(new URL('browser-smoke.json', out), JSON.stringify({ status: 'PASS', registers, outputHex: '4A', haltedStep: 24, replayed: true, errors }, null, 2));
console.log(JSON.stringify({ status: 'PASS', registers, outputHex: '4A', haltedStep: 24, replayed: true, errors }));
await browser.close();
